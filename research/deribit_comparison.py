"""Phase 3 gate: our IVs and Greeks against Deribit's on one recorded day.

Reads a sample of recorded snapshots pulled read-only from the server's database into a folder
outside the repo (CSV files: option_quotes, underlying_ticks, instruments, option_trades,
open_interest), runs ``optlab.evaluation.deribit_check`` on every minute in it, and writes
``research/deribit_comparison.md``: aggregate differences only, never the quotes themselves.

    uv run python research/deribit_comparison.py /path/to/day-2026-11-16
"""

import argparse
import subprocess
import time
from pathlib import Path

import numpy as np
import pandas as pd

from optlab.domain.market import Book
from optlab.evaluation import deribit_check as dc

REPORT = Path(__file__).with_name("deribit_comparison.md")


def md(df: pd.DataFrame, fmt: str = "{:.4f}") -> str:
    """A Markdown table (no extra dependency)."""
    df = df.reset_index()
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, float):
                cells.append("" if np.isnan(v) else fmt.format(v))
            elif isinstance(v, pd.Interval):
                cells.append(
                    f"{v.left:g}-{v.right:g}" if v.right < 1 or v.right > 1.0001 else f"{v.left:g}+"
                )
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("data", type=Path, help="folder with the pulled CSV files")
    parser.add_argument("--out", type=Path, default=REPORT)
    parser.add_argument("--every", type=int, default=1, help="use every Nth minute in the sample")
    args = parser.parse_args()

    q = pd.read_csv(args.data / "option_quotes.csv.gz")
    u = pd.read_csv(args.data / "underlying_ticks.csv.gz")
    ins = pd.read_csv(args.data / "instruments.csv.gz")
    minutes = sorted(q["ts_ms"].unique())[:: args.every]
    started = time.perf_counter()
    engine, surface, surfaces = [], [], []
    for ts in minutes:
        e, s, sf = dc.minute_frames(q[q.ts_ms == ts], u[u.ts_ms == ts], ins, int(ts))
        engine.append(e)
        surface.append(s)
        surfaces.extend(sf)
    seconds = time.perf_counter() - started
    eng = pd.concat(engine, ignore_index=True)
    srf = pd.concat(surface, ignore_index=True)
    day = pd.to_datetime(minutes[0], unit="ms").strftime("%Y-%m-%d")
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],  # noqa: S607
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()

    out: list[str] = [
        "# Phase 3 gate: our IVs and Greeks against Deribit's",
        "",
        f"Recorded day **{day} UTC**, {len(minutes)} snapshot minutes (every 10th minute of the "
        f"day), both books: {len(eng):,} option quotes for the engine check and {len(srf):,} "
        "for the surface check. Pulled read-only from the server's database on 18 Nov 2026; "
        f"the raw quotes stay outside the repo. Code at `{commit}` (plus the working tree); "
        f"{seconds:.0f} s to build {len(surfaces)} surfaces "
        f"({seconds / max(len(surfaces), 1) * 1000:.0f} ms each). Generated by "
        "`research/deribit_comparison.py`.",
        "",
        "Differences are absolute: IV in vol points, delta in delta units, gamma per USD, vega in "
        "USD per vol point, theta in USD a day (Deribit reports vega and theta in USD for both "
        "books). Buckets: |delta| by Deribit's delta, days to expiry from the ticker's time.",
        "",
    ]

    def section(title: str, text: str) -> None:
        out.extend([f"## {title}", "", text, ""])

    for book in (Book.LINEAR, Book.INVERSE):
        e = eng[eng.book == book.value]
        s = srf[srf.book == book.value]
        name = "BTC_USDC (linear, main book)" if book == Book.LINEAR else "BTC (inverse)"
        section(
            f"{name}: engine (our formulas, Deribit's inputs)",
            "Our IV re-solved from Deribit's mark price, and our Greeks at Deribit's mark IV, "
            "forward and ticker time. Deribit rounds the mark IV to 0.01 vol point and its "
            "Greeks to 5 decimals.",
        )
        out.extend(
            [
                "**IV (vol points), by days to expiry**",
                "",
                md(dc.summarise(e, "our_iv", "mark_iv", scale=100, by="days")),
                "",
            ]
        )
        day_plus = e[e.days >= 1]
        out.extend(
            [
                "**IV (vol points), by |delta|, expiries 1 day or more out**",
                "",
                md(dc.summarise(day_plus, "our_iv", "mark_iv", scale=100, by="delta")),
                "",
            ]
        )
        window = e[(e.days >= 7) & (e.days <= 30)]
        out.extend(
            [
                "**IV (vol points), by |delta|, expiries 7 to 30 days** "
                "(where the strategy trades)",
                "",
                md(dc.summarise(window, "our_iv", "mark_iv", scale=100, by="delta")),
                "",
            ]
        )
        # Within Deribit's rounding: the mark IV's 0.005 vol point plus half a price tick's IV.
        err = (e.our_iv - e.mark_iv).abs()
        bound = 0.00005 + e.iv_rounding + 1e-7
        w = e.assign(within=err <= bound, days_bucket=pd.cut(e.days, dc.DAY_BUCKETS, right=False))
        w = w[w.our_iv.notna()]
        share = w.groupby("days_bucket", observed=True)["within"].agg(["size", "mean"])
        share.columns = ["n", "share within rounding"]
        out.extend(
            [
                "**IV within Deribit's rounding alone** (|ours - mark| at most 0.005 vol point "
                "plus the IV that half a price tick moves):",
                "",
                md(share, "{:.4f}"),
                "",
                "Most re-solved IVs are further from the mark IV than rounding alone explains, by "
                "a median of a few hundredths of a vol point. Our Greeks at Deribit's mark IV "
                "match Deribit's Greeks to their 5-decimal rounding (below), so our formulas, "
                "forward, time and units agree with Deribit's; the small gap is between Deribit's "
                "own mark price and its mark IV in the same ticker (they are not exactly "
                "consistent with each other).",
                "",
            ]
        )
        for col, label, fmt in (
            ("delta", "Delta", "{:.6f}"),
            ("gamma", "Gamma (per USD)", "{:.2e}"),
            ("vega", "Vega (USD per vol point)", "{:.5f}"),
            ("theta", "Theta (USD a day)", "{:.5f}"),
        ):
            out.extend(
                [
                    f"**{label}, by days to expiry**",
                    "",
                    md(dc.summarise(e, f"our_{col}", col, by="days"), fmt),
                    "",
                ]
            )
        rel = e.assign(rel=((e.our_theta - e.theta).abs() / e.theta.abs().clip(lower=1e-9)))
        far = rel[(rel.days >= 7) & (rel.theta.abs() > 0.01)]
        out.extend(
            [
                f"Theta relative difference for expiries 7 days or more out: median "
                f"{far.rel.median():.2e}, 99th percentile {far.rel.quantile(0.99):.2e}. Within "
                "about 4 days of expiry Deribit's theta follows a different rule from the "
                "instantaneous Black-76 theta (in the last day it is close to the one-day change "
                "in value, capped by the time value), so theta is compared from 7 days out only.",
                "",
            ]
        )
        section(
            f"{name}: surface (our forward and smile against Deribit's marks)",
            "Our smile IV and our delta at every quoted strike inside each fitted expiry's range "
            "(all expiries, including those under 12 hours that the tenors don't use).",
        )
        out.extend(
            [
                "**IV (vol points), by days to expiry**",
                "",
                md(dc.summarise(s, "our_iv", "mark_iv", scale=100, by="days"), "{:.3f}"),
                "",
            ]
        )
        out.extend(
            [
                "**IV (vol points), by |delta|, expiries 7 to 30 days**",
                "",
                md(
                    dc.summarise(
                        s[(s.days >= 7) & (s.days <= 30)],
                        "our_iv",
                        "mark_iv",
                        scale=100,
                        by="delta",
                    ),
                    "{:.3f}",
                ),
                "",
            ]
        )
        out.extend(
            [
                "**Delta, by |delta|, expiries 7 to 30 days**",
                "",
                md(
                    dc.summarise(
                        s[(s.days >= 7) & (s.days <= 30)], "our_delta", "delta", by="delta"
                    ),
                    "{:.5f}",
                ),
                "",
            ]
        )
        fwd = s.groupby(["ts_ms", "expiry_ms"]).first()
        bp = (fwd.our_forward / fwd.deribit_forward - 1).abs() * 1e4
        out.extend(
            [
                f"Our forward against Deribit's `underlying_price`: median {bp.median():.2f} bp, "
                f"99th percentile {bp.quantile(0.99):.2f} bp, max {bp.max():.2f} bp.",
                "",
            ]
        )
        picks = dc.leg_choice(s)
        both = [p for p in picks if p.by_deribit is not None and p.by_ours is not None]
        differ = [p for p in both if p.by_deribit != p.by_ours]
        steps = []
        for p in differ:
            strikes = sorted(
                s[
                    (s.ts_ms == p.ts_ms) & (s.expiry_ms == p.expiry_ms) & (s.call == p.call)
                ].strike.unique()
            )
            if p.by_deribit in strikes and p.by_ours in strikes:
                steps.append(abs(strikes.index(p.by_deribit) - strikes.index(p.by_ours)))
        if not steps:
            how_far = ""
        elif max(steps) == 1:
            how_far = ", always the neighbouring strike"
        else:
            how_far = f", at most {max(steps)} strikes away"
        one_sided = sum(1 for p in picks if (p.by_deribit is None) != (p.by_ours is None))
        out.extend(
            [
                f"**0.20-delta short leg (|delta| 0.15 to 0.30, expiries 7 to 30 days):** "
                f"{len(both)} choices (minute x expiry x side); ours picks a different strike "
                f"from Deribit's delta in {len(differ)} ({len(differ) / max(len(both), 1):.1%})"
                f"{how_far}. A candidate on one side only: {one_sided}.",
                "",
            ]
        )
        sf = [x for x in surfaces if x.book == book]
        all_fits = [f for x in sf for f in x.fits]
        fits = [f for f in all_fits if f.smile is not None]
        diffs = [f.forward.difference_bp for f in all_fits]
        diff_bp = np.abs([d for d in diffs if d is not None])
        sources = pd.Series([f.forward.source.value for f in all_fits]).value_counts().to_dict()
        rmse = np.median([f.smile.rmse for f in fits if f.smile]) * 100
        fly = [f for f in fits if (f.butterfly_min or 0) < 0]
        fly_window = sum(1 for f in fly if 7 <= f.tau * 365 <= 30)
        fly_shortest = min((f.tau * 365 for f in fly), default=float("nan"))
        calendar = sum(1 for f in fits if f.calendar_ok is False)
        out.extend(
            [
                f"Forwards, dated future against put-call parity: median |difference| "
                f"{np.median(diff_bp):.2f} bp, 95th percentile {np.percentile(diff_bp, 95):.2f} "
                f"bp, max {np.max(diff_bp):.2f} bp over {len(diff_bp)} expiry-minutes. "
                f"Sources: {sources}.",
                "",
                f"Smile fits: {len(fits)}; median fit RMSE {rmse:.2f} vol points; butterfly "
                f"arbitrage in {len(fly)} fits ({fly_window} of them 7 to 30 days out; the "
                f"shortest such expiry {fly_shortest:.0f} days); calendar arbitrage in "
                f"{calendar}.",
                "",
            ]
        )

    oi_path = args.data / "open_interest.csv.gz"
    if oi_path.exists():
        oi = pd.read_csv(oi_path)
        tr = pd.read_csv(args.data / "option_trades.csv.gz")
        res = dc.open_interest_check(oi, tr[tr.recv_ts_ms.between(oi.ts_ms.min(), oi.ts_ms.max())])
        oi = oi.sort_values(["instrument_name", "ts_ms"])
        changed = oi.groupby("instrument_name")["open_interest"].diff().fillna(0) != 0
        section(
            "Open interest timing (add-on e)",
            f"Every minute from 12:00 to 18:00 UTC: {res['instrument_minutes']:,.0f} "
            f"instrument-minutes, {res['traded_minutes']:,.0f} with a trade received in the "
            f"minute before. Open interest changed in {res['changed_share_traded']:.1%} of traded "
            f"minutes and {res['changed_share_untraded']:.2%} of minutes without a trade; "
            f"{oi.loc[changed, 'instrument_name'].nunique()} of {oi['instrument_name'].nunique()} "
            f"options changed at all in six hours, in {oi.loc[changed, 'ts_ms'].nunique()} of "
            f"{oi['ts_ms'].nunique()} minutes (spread across the hour, not in batches). After a "
            f"trade, the first change came a median {res['lag_median_min']:.0f} minutes later "
            f"(90th percentile {res['lag_p90_min']:.0f}), over {res['trades_with_lag']:,.0f} "
            "traded instrument-minutes. So the ticker's open interest lags trading by up to hours "
            "and irregularly: it is stored as given, and no minute feature uses it.",
        )
    args.out.write_text("\n".join(out).rstrip("\n") + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
