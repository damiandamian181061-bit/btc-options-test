"""Data platform tables: data_quality, data_quality_runs, recorder_status and dataset_exports.

- data_quality: one row per finding of the hourly checks (a run of consecutive minutes with the
  same problem). ``skip`` rows mark periods that backtests leave out.
- data_quality_runs: one row per UTC hour checked, so the gap report can prove every recorded
  hour was looked at.
- recorder_status: the recorder's status line, once a minute (memory, connections, raw bytes
  written for the current UTC day).
- dataset_exports: one row per exported UTC day, with its manifest and dataset version, and when
  it was verified in R2.
- utc_ms(timestamptz): a timestamp as UTC milliseconds.

No recorded table is changed.

Revision ID: 0002
Revises: 0001
Create Date: 2026-11-14
"""

from alembic import op

revision = "0002"
down_revision = "0001"
branch_labels = None
depends_on = None


UPGRADE = r"""
-- A timestamp as UTC milliseconds, the platform's convention (inlined by the planner).
CREATE FUNCTION utc_ms(ts timestamptz) RETURNS bigint
    LANGUAGE sql STABLE PARALLEL SAFE
    AS $$ SELECT (extract(epoch FROM ts) * 1000)::bigint $$;

-- One row per finding: a run of consecutive snapshot minutes with the same problem, inside one
-- checked hour. end_ts is the first minute after the run (exclusive).
CREATE TABLE data_quality (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hour_ts     timestamptz NOT NULL,
    check_name  text NOT NULL,
    scope       text NOT NULL CHECK (scope IN ('global', 'index', 'instrument')),
    subject     text NOT NULL DEFAULT '',
    start_ts    timestamptz NOT NULL,
    end_ts      timestamptz NOT NULL,
    minutes     integer NOT NULL CHECK (minutes > 0),
    skip        boolean NOT NULL,
    detail      text NOT NULL DEFAULT '',
    detected_ms bigint NOT NULL,
    CHECK (end_ts > start_ts)
);
CREATE INDEX data_quality_hour_idx ON data_quality (hour_ts);
CREATE INDEX data_quality_skip_idx ON data_quality (start_ts) WHERE skip;

-- One row per UTC hour checked.
CREATE TABLE data_quality_runs (
    hour_ts          timestamptz PRIMARY KEY,
    checked_ms       bigint NOT NULL,
    checks_version   text NOT NULL,
    expected_minutes integer NOT NULL,
    present_minutes  integer NOT NULL,
    option_rows      bigint NOT NULL,
    findings         integer NOT NULL,
    skipped_minutes  integer NOT NULL
);

-- The recorder's status, once a minute. Memory in bytes; raw_bytes_day is what the raw stream
-- has written so far for raw_day (a UTC day).
CREATE TABLE recorder_status (
    ts               timestamptz NOT NULL,
    run_id           text NOT NULL,
    started_ms       bigint NOT NULL,
    rss_bytes        bigint,
    peak_rss_bytes   bigint,
    connections_up   integer NOT NULL,
    connections      integer NOT NULL,
    channels         integer NOT NULL,
    msgs_per_s       double precision NOT NULL,
    last_option_rows integer NOT NULL,
    db_jobs_waiting  integer NOT NULL,
    decode_errors    bigint NOT NULL,
    raw_day          date NOT NULL,
    raw_bytes_day    bigint NOT NULL,
    PRIMARY KEY (run_id, ts)
);
CREATE INDEX recorder_status_ts_idx ON recorder_status (ts);

-- One row per exported UTC day. uploaded_ms is set once every file is verified in R2;
-- local_pruned_ms once the server's own copies were removed (after 7 days).
CREATE TABLE dataset_exports (
    day             date PRIMARY KEY,
    dataset_version text NOT NULL,
    manifest        jsonb NOT NULL,
    rows            bigint NOT NULL,
    export_bytes    bigint NOT NULL,
    raw_files       integer NOT NULL,
    raw_bytes       bigint NOT NULL,
    exported_ms     bigint NOT NULL,
    uploaded_ms     bigint,
    local_pruned_ms bigint
);
"""


def upgrade() -> None:
    op.execute(UPGRADE)


def downgrade() -> None:
    # Dropping these tables would delete the data-quality history and the export records. Not
    # automated: CLAUDE.md needs Damian's explicit yes and a verified backup first.
    raise RuntimeError("0002 has no automatic downgrade: it would delete platform records")
